"use strict";

const {
  systemPassportFields,
  walkSchemaSections,
} = require("./passport-helpers");

const reservedPassportFieldKeySet = new Set([
  ...systemPassportFields,
  "modelName",
  "internalAliasId",
  "uniqueProductIdentifier",
  "passportPolicyKey",
  "contentSpecificationIds",
  "carrierPolicyKey",
  "economicOperatorId",
  "facilityId",
  "granularity",
  "digitalProductPassportId",
  "dppSchemaVersion",
  "dppStatus",
  "lastUpdate",
  "subjectDid",
  "dppDid",
  "companyDid",
]);

const reservedPassportSemanticIdSet = new Set([
  "dpp:digitalProductPassportId",
  "dpp:uniqueProductIdentifier",
  "dpp:granularity",
  "dpp:dppSchemaVersion",
  "dpp:dppStatus",
  "dpp:lastUpdate",
  "dpp:economicOperatorId",
  "dpp:facilityId",
  "dpp:contentSpecificationIds",
  "dpp:subjectDid",
  "dpp:dppDid",
  "dpp:companyDid",
  "dpp:dppId",
  "dpp:internalAliasId",
]);

const isReservedPassportFieldKey = (fieldKey) =>
  reservedPassportFieldKeySet.has(fieldKey);

const isReservedPassportSemanticId = (semanticId) =>
  reservedPassportSemanticIdSet.has(semanticId);

function findReservedPassportHeaderFieldConflicts(sections = []) {
  const conflicts = [];
  walkSchemaSections(sections, (section, sectionPath) => {
    const sectionKeys = sectionPath.map((entry) => entry.key).filter(Boolean);
    for (const field of Array.isArray(section?.fields) ? section.fields : []) {
      if (!field || typeof field !== "object") continue;
      if (isReservedPassportFieldKey(field.key)) {
        conflicts.push({
          field: field.key,
          sectionPath: sectionKeys,
          conflictType: "key",
          reservedField: field.key,
          message: `Field "${field.key}" is already generated by the passport registry/header and does not need to be created again.`,
        });
      }

      const semanticId = field.semanticId || null;
      if (isReservedPassportSemanticId(semanticId)) {
        conflicts.push({
          field: field.key,
          sectionPath: sectionKeys,
          semanticId,
          conflictType: "semanticId",
          reservedField: semanticId,
          message: `Field "${field.key}" uses reserved semanticId "${semanticId}", which is already generated by the passport registry/header and does not need to be created again.`,
        });
      }
    }
  });
  return conflicts;
}

module.exports = {
  findReservedPassportHeaderFieldConflicts,
  isReservedPassportFieldKey,
  isReservedPassportSemanticId,
};

export const supportedLanguageCodes = ["en", "sv", "de"];

const I18nContext = createContext({ t: (k) => k, lang: "en", setLang: () => {} });

const normalizeTranslationKey = (value) => String(value || "")
  .normalize("NFKD")
  .replace(/[\u0300-\u036f]/g, "")
  .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
  .replace(/[^a-zA-Z0-9]/g, "")
  .replace(/^[A-Z]/, chr => chr.toLowerCase());

export const translateText = (lang, key, values = {}) => {
  const message = (translations[lang] && translations[lang][key]) ||
    (translations.en && translations.en[key]) ||
    key;

  return String(message).replace(/{{\s*([\w.-]+)\s*}}/g, (_, name) =>
    values[name] === undefined || values[name] === null ? "" : String(values[name])
  );
};

export const translateSchemaLabel = (lang, source, explicitKey) => {
  const localeSpecificLabel = source?.translations?.[lang] ||
    source?.labelI18n?.[lang] ||
    source?.titleI18n?.[lang];
  if (localeSpecificLabel) return translateText(lang, localeSpecificLabel);

  const candidates = [
    source?.translations?.en,
    source?.labelI18n?.en,
    source?.titleI18n?.en,
    explicitKey,
    source?.i18nKey,
    source?.translationKey,
    source?.key,
    normalizeTranslationKey(source?.label),
    normalizeTranslationKey(source?.title),
    source?.label,
    source?.title,
  ].filter(Boolean);

  for (const candidate of candidates) {
    const translated = translateText(lang, candidate);
    if (translated !== candidate) return translated;
  }

  return source?.label || source?.title || explicitKey || "";
};

export const translateFieldValue = (lang, value, type) => {
  if (type === "boolean") return value ? translateText(lang, "yes") : translateText(lang, "no");
  return value;
};

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(
    () => {
      const storedLanguage = localStorage.getItem("dppLang");
      return supportedLanguageCodes.includes(storedLanguage) ? storedLanguage : "en";
    }
  );

  const setLang = (l) => {
    const nextLanguage = supportedLanguageCodes.includes(l) ? l : "en";
    localStorage.setItem("dppLang", nextLanguage);
    setLangState(nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key, values) => translateText(lang, key, values);

  return (
    <I18nContext.Provider value={{ t, lang, setLang }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);

